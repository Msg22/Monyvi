/**
 * Generate canonical T009 account-review vocabularies from the checked-in
 * Supabase public enums and existing parser reason type (no copied unions).
 * Run: node scripts/generate-account-review-vocabulary.cjs
 */
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const supabaseTypes = fs.readFileSync(
  path.join(root, "packages/db/src/supabase-types.ts"), "utf8"
);
const localTypes = fs.readFileSync(
  path.join(root, "packages/logic/src/types.ts"), "utf8"
);
const constantsStart = supabaseTypes.indexOf("export const Constants =");
if (constantsStart === -1) throw new Error("Generated Supabase Constants missing");
const constants = supabaseTypes.slice(constantsStart);

function parseValues(fragment, label) {
  const values = [...fragment.matchAll(/"([^"]+)"/gu)].map((match) => match[1]);
  if (values.length === 0 || new Set(values).size !== values.length) {
    throw new Error("Invalid or duplicated source vocabulary: " + label);
  }
  return values;
}
function getEnum(name) {
  const match = new RegExp("\\b" + name + ":\\s*\\[([^\\]]+)\\]", "u").exec(constants);
  if (!match) throw new Error("Missing generated enum: " + name);
  return parseValues(match[1], name);
}

const reasonMatch =
  /export type TransactionReviewReason\s*=\s*([\s\S]*?);/u.exec(localTypes);
if (!reasonMatch) throw new Error("Missing TransactionReviewReason type");
const projections = [
  ["ACCOUNT_REVIEW_ACCOUNT_TYPES", "AccountType", getEnum("account_type")],
  ["ACCOUNT_REVIEW_CURRENCIES", "CurrencyType", getEnum("currency_type")],
  ["ACCOUNT_REVIEW_TRANSACTION_TYPES", "TransactionType", getEnum("transaction_type")],
  ["ACCOUNT_REVIEW_TRANSACTION_SOURCES", "TransactionSource", getEnum("transaction_source")],
  ["ACCOUNT_REVIEW_EXISTING_REASONS", "TransactionReviewReason", parseValues(reasonMatch[1], "TransactionReviewReason")],
];
const lines = [
  "/**",
  " * AUTO-GENERATED projection of the checked-in database/domain vocabulary.",
  " * Source: packages/db/src/supabase-types.ts (public Constants.Enums) and",
  " * packages/logic/src/types.ts (TransactionReviewReason).",
  " * Generated by scripts/generate-account-review-vocabulary.cjs.",
  " * Logic imports only type definitions from @monyvi/db; no runtime DB import.",
  " */",
  'import type { AccountType, CurrencyType, TransactionType, TransactionSource } from "@monyvi/db";',
  'import type { TransactionReviewReason } from "../types";',
  "",
];
for (const [name, valueType, values] of projections) {
  lines.push(
    "export const " + name + " = " + JSON.stringify(values, null, 2) +
      " as const satisfies readonly " + valueType + "[];",
    ""
  );
}
lines.push(
  "type AssertFullyProjected<T extends never> = T;",
  "export type ReviewAccountVocabularyComplete = AssertFullyProjected<",
  "  Exclude<AccountType, (typeof ACCOUNT_REVIEW_ACCOUNT_TYPES)[number]>",
  ">;",
  "export type ReviewCurrencyVocabularyComplete = AssertFullyProjected<",
  "  Exclude<CurrencyType, (typeof ACCOUNT_REVIEW_CURRENCIES)[number]>",
  ">;",
  "export type ReviewTransactionVocabularyComplete = AssertFullyProjected<",
  "  Exclude<TransactionType, (typeof ACCOUNT_REVIEW_TRANSACTION_TYPES)[number]>",
  ">;",
  "export type ReviewSourceVocabularyComplete = AssertFullyProjected<",
  "  Exclude<TransactionSource, (typeof ACCOUNT_REVIEW_TRANSACTION_SOURCES)[number]>",
  ">;",
  "export type ReviewReasonVocabularyComplete = AssertFullyProjected<",
  "  Exclude<TransactionReviewReason, (typeof ACCOUNT_REVIEW_EXISTING_REASONS)[number]>",
  ">;",
  ""
);
const outputPath = path.join(root, "packages/logic/src/account-review/generated-vocabulary.ts");
fs.writeFileSync(outputPath, lines.join("\n"), "utf8");
process.stdout.write("Generated " + outputPath + " from " + projections.length + " vocabularies\n");
