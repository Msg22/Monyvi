/**
 * NONPRODUCTION: deterministic synthetic AAC-LC/M4A negative-fixture builder.
 * Requires an existing local FFmpeg binary. No package or provider calls.
 * Valid human speech is intentionally NOT generated or mislabeled.
 */
interface Fixture {
  readonly id: string;
  readonly relativePath: string | null;
  readonly durationBucketSeconds: number;
  readonly expectedClass: "no_speech" | "speech" | "invalid";
  readonly origin: string;
  readonly license: string | null;
  readonly sha256: string | null;
  readonly status: "ready" | "missing";
  readonly notes: string;
}

const ROOT = new URL("./local/", import.meta.url);
const DURATIONS = [5, 15, 30] as const;
const PRESETS = [
  { name: "silence", graph: "anullsrc=r=44100:cl=stereo" },
  { name: "fan-proxy", graph: "anoisesrc=color=pink:amplitude=0.01:seed=391:sample_rate=44100" },
  { name: "traffic-proxy", graph: "anoisesrc=color=white:amplitude=0.015:seed=391:sample_rate=44100" },
] as const;

function emit(message: string): void {
  Deno.stdout.writeSync(new TextEncoder().encode(message + "\n"));
}

async function checksum(bytes: Uint8Array): Promise<string> {
  const hash = await crypto.subtle.digest("SHA-256", bytes);
  return Array.from(new Uint8Array(hash), (x) => x.toString(16).padStart(2, "0")).join("");
}

async function run(args: string[]): Promise<void> {
  const output = await new Deno.Command("ffmpeg", {
    args: ["-hide_banner", "-loglevel", "error", "-nostdin", "-y", ...args],
    stdout: "piped",
    stderr: "piped",
  }).output();
  if (!output.success) {
    const detail = new TextDecoder().decode(output.stderr);
    throw new Error("FFmpeg failed: " + detail);
  }
}

async function main(): Promise<void> {
  await Deno.mkdir(ROOT, { recursive: true });
  const fixtures: Fixture[] = [];
  for (const spec of PRESETS) {
    for (const duration of DURATIONS) {
      const id = spec.name + "-" + String(duration).padStart(2, "0");
      const file = new URL(id + ".m4a", ROOT);
      await run([
        "-f", "lavfi", "-i", spec.graph,
        "-t", String(duration),
        "-ac", "2", "-ar", "44100",
        "-c:a", "aac", "-profile:a", "aac_low", "-b:a", "128k",
        file.pathname.replace(/^\/([A-Za-z]:\/)/, "$1"),
      ]);
      const digest = await checksum(await Deno.readFile(file));
      fixtures.push({
        id,
        relativePath: id + ".m4a",
        durationBucketSeconds: duration,
        expectedClass: "no_speech",
        origin: "synthetic: FFmpeg lavfi " + spec.graph,
        license: "synthetically generated by this script",
        sha256: digest,
        status: "ready",
        notes: "Proxy environment, not recorded field noise.",
      });
    }
  }
  for (const duration of DURATIONS) {
    for (const label of ["quiet-eg-ar", "quiet-en", "code-switch"]) {
      fixtures.push({
        id: label + "-" + String(duration).padStart(2, "0"),
        relativePath: null,
        durationBucketSeconds: duration,
        expectedClass: "speech",
        origin: "UNPROVIDED: obtain synthetic/licensed non-private speech",
        license: null,
        sha256: null,
        status: "missing",
        notes: "Required before high-recall or speech-preservation conclusions.",
      });
    }
  }
  // Intentional invalid-input control, not a VAD example.
  const invalid = new URL("unknown-bytes.bin", ROOT);
  const bytes = Uint8Array.from({ length: 1000 }, (_, i) => (i * 73 + 41) & 0xff);
  await Deno.writeFile(invalid, bytes);
  fixtures.push({
    id: "unknown-bytes",
    relativePath: "unknown-bytes.bin",
    durationBucketSeconds: 0,
    expectedClass: "invalid",
    origin: "synthetic: deterministic non-media bytes",
    license: "synthetically generated by this script",
    sha256: await checksum(bytes),
    status: "ready",
    notes: "Must fail decoder/structural validation, not consume provider start.",
  });
  const manifest = {
    schemaVersion: 1,
    purpose: "Nonproduction Deno/Edge feasibility; no product acceptance decision",
    recorderProfile: "AAC-LC/M4A 44.1 kHz stereo nominal (verify source artifacts)",
    fixtures,
  };
  await Deno.writeTextFile(new URL("fixtures.json", ROOT), JSON.stringify(manifest, null, 2) + "\n");
  emit("Generated " + fixtures.filter((fixture) => fixture.status === "ready").length + " synthetic fixtures.");
  emit("Quiet Arabic/English/code-switch POSITIVES ARE MISSING; complete-suite decision BLOCKED.");
}

if (import.meta.main) {
  await main();
}
