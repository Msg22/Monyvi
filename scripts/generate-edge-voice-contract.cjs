const fs = require("node:fs");
const path = require("node:path");

const repoRoot = path.resolve(__dirname, "..");
const canonicalPath = path.join(
  repoRoot,
  "packages/logic/src/voice-ai-safeguard-contract.ts"
);
const edgeCopyPath = path.join(
  repoRoot,
  "supabase/functions/_shared/voice-ai-safeguard-contract.ts"
);

function generateEdgeContractCopy() {
  if (!fs.existsSync(canonicalPath)) {
    throw new Error(`Canonical contract not found at: ${canonicalPath}`);
  }

  const content = fs.readFileSync(canonicalPath, "utf8");

  // Write byte-identically to supabase/functions/_shared/voice-ai-safeguard-contract.ts
  fs.writeFileSync(edgeCopyPath, content, "utf8");
  console.log(`Generated byte-identical Edge copy at ${edgeCopyPath}`);
}

generateEdgeContractCopy();
